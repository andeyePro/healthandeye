import Foundation

/// README.md at the root of the Health&I folder: what each file is, for a reader with no other context.
public enum ReadmeDoc {
    public static func render() -> String {
        """
        # Health&I data folder

        This folder is written by Health&I, a personal health, training and diet app for iPhone, iPad
        and Apple Watch. It is both the app's own store and an export meant to be read by people and
        by AI assistants (Claude) to give bespoke training, health and diet advice. Everything here
        is plain text: JSON, Markdown and CSV. Nothing is uploaded anywhere; the folder holds health
        data, so treat it as private.

        Field-by-field definitions, units and allowed values are in `schema.md`. Start with
        `digest.md` for a quick picture of recent training against targets.

        ## Files

        | Path | What it is | Who writes it |
        |---|---|---|
        | `README.md` | This file. Regenerated by the app; edits are overwritten. | app |
        | `schema.md` | Every file, field, unit and allowed value. Regenerated by the app. | app |
        | `digest.md` | Rolling summary: last 7 and 28 days against each enabled target, best sets and trends per exercise, flags (e.g. no session for 5 days, a target missed 3 weeks running), open advice. Regenerated after each session and daily. | app |
        | `log.csv` | Flat table for spreadsheets: one row per set and one summary row per rowing session. Regenerated. | app |
        | `catalogue/profile.json` | The person: height, date of birth, sex, max and resting HR, units, time zone, body mass. | app or you |
        | `catalogue/equipment.json` | Machines, bars, plates, collars, benches, dumbbells, bands; their masses, limits, Bluetooth details and known quirks. | app or you |
        | `catalogue/exercises.json` | User-defined exercises: pattern, unilateral or not, how measured, equipment used, rest time, target rep range. | app or you |
        | `catalogue/zones.json` | Named heart-rate or power zone sets, e.g. "Zone 2" = 110-120 bpm. | app or you |
        | `catalogue/targets.json` | Goals for any metric per day or week, e.g. 175 minutes per week in Zone 2, 130 g protein per day. | app or you |
        | `catalogue/foods.json` | Food library: nutrients per 100 g and named servings. | app or you |
        | `catalogue/settings.json` | Which modules are on, effort scale (RIR or RPE), set notation, live display tiles, progression-hint thresholds. | app or you |
        | `sessions/YYYY/YYYY-MM-DD-HHMM-<type>.json` | One training session (rowing, weights, ...): sets, sensor time series, summary numbers. | app |
        | `sessions/YYYY/YYYY-MM-DD-HHMM-<type>.md` | The same session as readable Markdown (sets table, rowing summary, per-minute intervals). | app |
        | `daily/YYYY/YYYY-MM-DD.json` | One day: Apple Health metrics, food eaten, nutrient totals, progress against daily targets. | app |
        | `body/measures.json` | Body measurements over time (weight, body fat, waist, ...) with their source. | app |
        | `advice/<YYYY-MM-DD>-<topic>.md` | Advice notes written by Claude (or anyone). The app shows each as a card and never edits these files. | Claude / you |
        | `advice/status.json` | Status of each advice note: open, done or rejected, keyed by file name without `.md`. | app only |

        ## Editing the catalogue

        Files under `catalogue/` may be edited by hand or by Claude. On next launch the app re-reads
        them and shows a confirmation listing what changed. Keep ids stable: ids are readable slugs
        (e.g. `ex-goblet-squat`, `eq-woodrower`) and sessions refer to exercises and equipment by id.
        Every field except `id` and `name` is optional and unknown keys are ignored, so small partial
        records are fine. Session and daily files are records of what happened; the app treats them
        as read-only history.

        ## Advice round-trip

        1. Claude reads this folder (start with `digest.md`, then sessions and `catalogue/`).
        2. Claude writes advice as Markdown: `advice/<YYYY-MM-DD>-<topic>.md`, e.g.
           `advice/2026-11-07-zone-2-volume.md`. The first `# ` heading is the title; the date comes
           from the file name. Write one file per piece of advice so each can be acted on separately.
        3. The app shows each note as a card. The person marks it done or rejected.
        4. The app records that in `advice/status.json` only, e.g.
           `{"2026-11-07-zone-2-volume": "done"}`. It never rewrites the advice file itself. A note
           missing from `status.json` is open.
        5. Next time, Claude reads `status.json` (and the "Open advice" list in `digest.md`) to see
           what was acted on.

        ## Conventions

        - JSON is pretty-printed with sorted, snake_case keys. Dates are ISO 8601 with time zone
          (e.g. `2026-11-07T07:30:00Z`); day files use `YYYY-MM-DD`.
        - Units are in the field name or stated in `schema.md`: kg, cm, seconds, metres, bpm, kcal, grams.
        - Every measured value says where it came from (`source`: polar_h10, apple_watch, machine,
          manual, health_kit, estimate). Conflicting sources are kept side by side, never merged.
        - Rowing energy: `energy_kcal_hr` is estimated from heart rate; `energy_kcal_console` is what
          the rower displayed. They differ by design; prefer the HR estimate.
        """ + "\n"
    }
}
